// Dev deploy helper (ADR-16): turns the built web app (dist/client) into a module the
// Worker can serve itself, so no separate asset upload is needed from this environment.
import { readdirSync, readFileSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import { join, relative, extname } from "node:path";

const ROOT = "dist/client";
const TYPES = { ".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".css": "text/css; charset=utf-8",
  ".svg": "image/svg+xml", ".png": "image/png", ".ico": "image/x-icon", ".json": "application/json", ".txt": "text/plain; charset=utf-8" };
const files = [];
const walk = (d) => { for (const f of readdirSync(d)) { const p = join(d, f); statSync(p).isDirectory() ? walk(p) : files.push(p); } };
walk(ROOT);
const entries = files.filter((p) => !p.endsWith(".assetsignore")).map((p) => {
  const path = "/" + relative(ROOT, p).split("\\").join("/");
  const type = TYPES[extname(p)] ?? "application/octet-stream";
  return `  ${JSON.stringify(path)}: { type: ${JSON.stringify(type)}, body: ${JSON.stringify(readFileSync(p).toString("base64"))} },`;
});
mkdirSync("src/worker/generated", { recursive: true });
writeFileSync("src/worker/generated/assets.ts",
  `// GENERATED by scripts/embed-assets.mjs. Do not edit or commit.\nexport const ASSETS: Record<string, { type: string; body: string }> = {\n${entries.join("\n")}\n};\n`);
console.log(`Embedded ${entries.length} files from ${ROOT}`);
